#!/usr/bin/env python3
"""gen_pure_extra.py - write src/pure_extra_data.h: the pk3s a pure server accepts on its
clients WITHOUT holding the files (src/pure_extra.c).

    python3 scripts/gen_pure_extra.py <pk3> [<pk3> ...] [-o src/pure_extra_data.h]
    python3 scripts/gen_pure_extra.py --check <pk3> [--feed N]     # print the checksums only

What identifies a pk3 to the engine (FS_LoadZipFile, cod_lnxded 0x80633c6) is not its
bytes but the CRC-32 of every non-empty file in its central directory, in directory order:

    checksum      = Com_BlockChecksum(crcs)                    -> sv_paks
    pure checksum = Com_BlockChecksumKey(crcs, checksumFeed)   -> what a client answers ("cp")

(MD4, the four digest words xored.) So the CRC list is all the server needs to list the
pak in sv_paks and to recognise a client that loaded it - a few kB instead of 6 GB.
The header carries that list per pak; the pure checksum is derived at run time, the feed
changes at every map.
"""
import argparse
import os
import struct
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))


# ------------------------------------------------------------------ MD4 (RFC 1320)
def _md4(data):
    def lrot(x, n):
        return ((x << n) | (x >> (32 - n))) & 0xffffffff
    a, b, c, d = 0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476
    n = len(data)
    data += b"\x80" + b"\0" * ((55 - n) % 64) + struct.pack("<Q", n * 8)
    for off in range(0, len(data), 64):
        x = struct.unpack_from("<16I", data, off)
        aa, bb, cc, dd = a, b, c, d
        order1 = list(range(16))
        for i, k in enumerate(order1):
            s = (3, 7, 11, 19)[i % 4]
            f = (b & c) | (~b & d)
            a, b, c, d = d, lrot((a + f + x[k]) & 0xffffffff, s), b, c
        order2 = [0, 4, 8, 12, 1, 5, 9, 13, 2, 6, 10, 14, 3, 7, 11, 15]
        for i, k in enumerate(order2):
            s = (3, 5, 9, 13)[i % 4]
            g = (b & c) | (b & d) | (c & d)
            a, b, c, d = d, lrot((a + g + x[k] + 0x5a827999) & 0xffffffff, s), b, c
        order3 = [0, 8, 4, 12, 2, 10, 6, 14, 1, 9, 5, 13, 3, 11, 7, 15]
        for i, k in enumerate(order3):
            s = (3, 9, 11, 15)[i % 4]
            h = b ^ c ^ d
            a, b, c, d = d, lrot((a + h + x[k] + 0x6ed9eba1) & 0xffffffff, s), b, c
        a, b, c, d = (a + aa) & 0xffffffff, (b + bb) & 0xffffffff, (c + cc) & 0xffffffff, (d + dd) & 0xffffffff
    return a, b, c, d


def block_checksum(buf, key=None):
    if key is not None:
        buf = struct.pack("<i", key) + buf
    a, b, c, d = _md4(buf)
    v = a ^ b ^ c ^ d
    return v - (1 << 32) if v & 0x80000000 else v          # the engine prints it with %i


def pak_crcs(path):
    """CRC-32 of every file with a non-zero uncompressed size, central-directory order."""
    with zipfile.ZipFile(path) as z:
        return [i.CRC for i in z.infolist() if i.file_size > 0]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pk3", nargs="+")
    ap.add_argument("--check", action="store_true", help="print name / files / checksum, write nothing")
    ap.add_argument("--feed", type=int, default=None, help="with --check: also the pure checksum for this feed")
    ap.add_argument("-o", "--out", default=os.path.join(HERE, "..", "src", "pure_extra_data.h"))
    a = ap.parse_args()

    paks = []
    for p in a.pk3:
        crcs = pak_crcs(p)
        raw = struct.pack("<%dI" % len(crcs), *crcs)
        name = os.path.splitext(os.path.basename(p))[0]
        paks.append((name, crcs, block_checksum(raw), os.path.getsize(p)))
        line = "%-28s %6d files  checksum %d" % (name, len(crcs), paks[-1][2])
        if a.feed is not None:
            line += "  pure(feed %d) %d" % (a.feed, block_checksum(raw, a.feed))
        print(line)
    if a.check:
        return 0

    out = ["/* pure_extra_data.h - GENERATED by scripts/gen_pure_extra.py, do not edit.",
           " *",
           " * The pk3s a pure server accepts without holding them: per pak, the CRC-32 of every",
           " * non-empty file in central-directory order (what FS_LoadZipFile checksums). */",
           "#ifndef PURE_EXTRA_DATA_H", "#define PURE_EXTRA_DATA_H", ""]
    for k, (name, crcs, ck, size) in enumerate(paks):
        out.append("/* %s.pk3 - %d files, %.1f MB, checksum %d */" % (name, len(crcs), size / 1048576, ck))
        out.append("static const unsigned int PX_CRC_%d[%d] = {" % (k, len(crcs)))
        for i in range(0, len(crcs), 8):
            out.append("    " + " ".join("0x%08x," % c for c in crcs[i:i + 8]))
        out.append("};")
    out.append("")
    out.append("typedef struct { const char *name; const unsigned int *crc; int ncrc; int checksum; } px_pak_t;")
    out.append("static const px_pak_t PX_PAKS[] = {")
    for k, (name, crcs, ck, size) in enumerate(paks):
        out.append('    { "%s", PX_CRC_%d, %d, %d },' % (name, k, len(crcs), ck))
    out.append("};")
    out.append("#define PX_NUM_PAKS ((int)(sizeof(PX_PAKS) / sizeof(PX_PAKS[0])))")
    out.append("")
    out.append("#endif")
    with open(a.out, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%s: %d pak(s), %d CRCs" % (a.out, len(paks), sum(len(p[1]) for p in paks)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
