/*
 * hitbox_fix.c - the bullet hit volume covers the visible mesh (COD1RELOADED_HITBOX_FIX).
 *
 * What the engine tests (cod_lnxded 0x80d2000, called from SV_ClipMoveToEntity for a
 * locational trace against a player): for every model of the entity's DObj with collision
 * on, for every bone with a non-zero box, it moves the ray into the bone frame and slab-
 * tests it against the bone's box - 40-byte entries { mins[3], maxs[3], centre[3], r^2 },
 * mins/maxs copied from xmodelparts (24 bytes after each bone name), centre / r^2 = the
 * circumscribed sphere used as a pre-test. The hit volume is the union of those oriented
 * boxes, and codps3/xanim_tool/hitvol_boxes.py reproduces the server's own hit map from
 * the file boxes cell for cell (5387/5395 side, 5052/5055 front).
 *
 * The shipped boxes do not cover the whole mesh. Worse: the 15 LOD0 xmodelparts of the 17
 * MP bodies all carry the SAME 80 boxes (FNV-1a d5318302, the US airborne rig's), whatever
 * the mesh - in bind pose 20-31 % of a body's vertices lie outside every box, by up to 4 u:
 * the collar behind the neck (all models), the overcoat skirt of the Russian winter body
 * (12 % of its visible leg cells from the side), hands and forearms. A bullet visibly on
 * the player goes to the world there: that is the "je suis sur le personnage et ca ne hit
 * pas" report.
 *
 * Fix: hitbox_data.h (generated by codps3/xanim_tool/gen_hitboxes.py) holds, per body
 * model, the bones whose box must grow, as the union of the shipped box and the bind-pose
 * position of the vertices assigned to the bone (+0.25 u). This hooks the test above and,
 * the first time it sees a model's bone table, fingerprints its 80 boxes (the same hash the
 * generator computed from the files): a vanilla table is patched in place with the set of
 * that model - looked up by the XModel's name (char* at +0 of the struct, e.g.
 * "playerbody_russian_conscript_winter") - or with the universal set (union over all
 * bodies) for a body model the table does not know; mins, maxs, centre and r^2 are all
 * rewritten. A table that is not the vanilla one is left alone. Server side only: the
 * server decides every hit.
 *
 * COD1RELOADED_HITBOX_FIX=0 disables it. COD1RELOADED_HITBOX_DEBUG=1 dumps the first
 * XModel structs seen (how the name offset was found).
 */
#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <strings.h>
#include <stdint.h>

#include "hooks.h"
#include "hitbox_fix.h"
#include "hitbox_data.h"

#define TAG "[hitbox_fix]"
#define VA_PART_TEST 0x080d2000u           /* cod_lnxded 1.5, md5 d3ac406b */
#define PATCH_LEN    10                    /* push ebp; mov ebp,esp; push ebx; sub esp,0x234 */
#define XMODEL_NAME  0x00                  /* XModel: +0 char* name, +4 lod data, +0xc char* "xmodel/name" */

typedef struct { float mins[3], maxs[3], center[3], r2; } hb_entry_t;   /* 40 bytes */
typedef int (*part_test_t)(void* obj, const float* start, const float* end,
                           const unsigned char* prio, void* out);

static const unsigned char PROLOGUE[PATCH_LEN] =
    { 0x55, 0x89, 0xe5, 0x53, 0x81, 0xec, 0x34, 0x02, 0x00, 0x00 };

static hook_t      g_hook;
static part_test_t g_orig     = NULL;
static int         g_enabled  = 1;
static int         g_verified = 0;
static int         g_dbg      = 0;
static int         g_head_on_mesh = 1;     /* COD1RELOADED_HEAD_ON_MESH=0: leave the head box on "head" */

/* bone tables already looked at (a table is reloaded with every map, at any address, so
 * the first entry's bytes are kept and re-checked: a new table at an old address is seen) */
#define SEEN_MAX 64
typedef struct { void* parts; hb_entry_t first; } seen_t;
static seen_t g_seen[SEEN_MAX];
static int    g_nseen = 0;
static int    g_unknown_reported = 0;

static unsigned fnv1a(const unsigned char* p, size_t n, unsigned h) {
    size_t i;
    for (i = 0; i < n; ++i) { h ^= p[i]; h *= 0x01000193u; }
    return h;
}

/* is [p, p+n) mapped readable? (/proc/self/maps; used once per new table, never in the
 * hot path) */
static int readable(const void* p, size_t n) {
    FILE* f;
    char line[512];
    int ok = 0;
    uintptr_t a = (uintptr_t)p;
    if (!p) return 0;
    f = fopen("/proc/self/maps", "r");
    if (!f) return 0;
    while (fgets(line, sizeof(line), f)) {
        unsigned long lo, hi; char perm[8];
        if (sscanf(line, "%lx-%lx %7s", &lo, &hi, perm) != 3) continue;
        if (a >= lo && a + n <= hi && perm[0] == 'r') { ok = 1; break; }
    }
    fclose(f);
    return ok;
}

static void set_entry(hb_entry_t* e, const float* mins, const float* maxs) {
    int a;
    float h[3];
    memcpy(e->mins, mins, sizeof(e->mins));
    memcpy(e->maxs, maxs, sizeof(e->maxs));
    for (a = 0; a < 3; ++a) {
        e->center[a] = 0.5f * (mins[a] + maxs[a]);
        h[a] = 0.5f * (maxs[a] - mins[a]);
    }
    e->r2 = h[0] * h[0] + h[1] * h[1] + h[2] * h[2];
}

static const hb_set_t* set_for(const char* name) {
    unsigned k;
    if (!name) return &HB_UNIVERSAL;
    for (k = 0; k < HB_NUM_LOOKUP; ++k)
        if (!strcasecmp(HB_LOOKUP[k].xmodel, name)) return &HB_SETS[HB_LOOKUP[k].set];
    return &HB_UNIVERSAL;
}

/* the bone table of one model: numBones from the header the engine reads (**parts,
 * short), entries at *(parts + 8) */
static void patch_parts(void* parts, const char* model) {
    char*       p       = (char*)parts;
    const char* hdr     = *(const char**)(*(char**)p);
    const int   nbones  = *(const short*)hdr;
    hb_entry_t* e       = *(hb_entry_t**)(p + 8);
    unsigned    fp      = 0x811c9dc5u;
    unsigned    i;
    seen_t*     s;
    const char* name;
    if (!e || nbones <= 0 || nbones > 256) return;
    /* seen before, and still the same table at that address? */
    for (i = 0; i < (unsigned)g_nseen; ++i)
        if (g_seen[i].parts == parts && memcmp(&g_seen[i].first, &e[0], sizeof(hb_entry_t)) == 0)
            return;
    for (i = 0; i < (unsigned)nbones; ++i)
        fp = fnv1a((const unsigned char*)&e[i], 24, fp);
    if (fp == HB_SHIPPED_FP && nbones == HB_NBONES) {
        const hb_set_t* set;
        unsigned k;
        name = *(const char**)(model + XMODEL_NAME);
        if (!readable(name, 64)) name = NULL;
        if (!g_verified) {
            /* prove the centre / r^2 layout once on a bone that has a box: it must be the
             * circumscribed sphere of that box, or the RE is wrong and nothing is touched */
            hb_entry_t chk;
            int b;
            for (b = 0; b < nbones; ++b) if (e[b].r2 != 0.0f) break;
            set_entry(&chk, e[b].mins, e[b].maxs);
            printf("%s layout check bone %d: mins %.2f %.2f %.2f maxs %.2f %.2f %.2f centre %.3f %.3f %.3f"
                   " (expect %.3f %.3f %.3f) r2 %.3f (expect %.3f)\n", TAG, b,
                   e[b].mins[0], e[b].mins[1], e[b].mins[2], e[b].maxs[0], e[b].maxs[1], e[b].maxs[2],
                   e[b].center[0], e[b].center[1], e[b].center[2], chk.center[0], chk.center[1], chk.center[2],
                   e[b].r2, chk.r2);
            if (memcmp(chk.center, e[b].center, sizeof(chk.center)) != 0 ||
                (chk.r2 - e[b].r2) * (chk.r2 - e[b].r2) > 1e-3f * chk.r2 * chk.r2) {
                printf("%s entry layout is NOT {mins, maxs, centre, r2} - fix DISABLED\n", TAG);
                g_enabled = 0;
                fflush(stdout);
                return;
            }
            g_verified = 1;
        }
        set = set_for(name);
        for (k = 0; k < set->nfix; ++k) {
            const hb_fix_t* f = &set->fix[k];
            if (f->bone < (unsigned)nbones) set_entry(&e[f->bone], f->mins, f->maxs);
        }
        /* THE HEAD BOX GOES ON THE BONE THE HEAD MESH RIDES. The shipped table puts the head
         * box on the controller bone "head" (a leaf under "bip01 head", same place, identity
         * bind offset), but every head model is skinned to "bip01 head" (348 of basehead's
         * 487 vertices, the rest on jaw / lips under it): the head controller's rotation
         * (aim pitch, lean roll, aim-walk) turns the BOX and not the visible head. Measured
         * live on a walking, aiming player: 13.6 degrees between the two bones = the top of
         * the box 2.5 u off the skull. "bip01 head" already carries the head hit location
         * (class 2) and has no box: it gets the head box, "head" gets none. */
        if (g_head_on_mesh) {
            int b_head = -1, b_bip = -1;
            for (k = 0; k < HB_NBONES; ++k) {
                if (!strcmp(HB_BONE_NAMES[k], "head")) b_head = (int)k;
                if (!strcmp(HB_BONE_NAMES[k], "bip01 head")) b_bip = (int)k;
            }
            if (b_head >= 0 && b_bip >= 0 && b_head < nbones && b_bip < nbones && e[b_bip].r2 == 0.0f) {
                const unsigned char* cls = *(const unsigned char* const*)(p + 0x14);
                if (cls && cls[b_bip] == cls[b_head]) {
                    e[b_bip] = e[b_head];
                    memset(&e[b_head], 0, sizeof(hb_entry_t));
                } else {
                    printf("%s head box NOT moved: hit location of bip01 head (%d) differs from head (%d)\n", TAG,
                           cls ? cls[b_bip] : -1, cls ? cls[b_head] : -1);
                }
            }
        }
        printf("%s %s: %u boxes grown to the mesh (set %s, table %p)\n", TAG,
               name ? name : "(no name)", set->nfix, set->parts, parts);
        fflush(stdout);
    } else if (nbones == HB_NBONES && g_unknown_reported < 4) {
        g_unknown_reported++;
        printf("%s 80-bone table %p is not the vanilla one (fp 0x%08x) - left alone\n", TAG, parts, fp);
        fflush(stdout);
    }
    /* remember it (patched or not) */
    s = (g_nseen < SEEN_MAX) ? &g_seen[g_nseen++] : &g_seen[g_nseen % SEEN_MAX];
    s->parts = parts;
    memcpy(&s->first, &e[0], sizeof(hb_entry_t));
}

/* DObj: numModels = byte +0x16, model i = *(obj + 0x1c + 4*i), its bone table =
 * *(*(*(model + 4)) + 4) - exactly the loads at 0x80d210a..0x80d2130 */
static int hook_part_test(void* obj, const float* start, const float* end,
                          const unsigned char* prio, void* out) {
    if (g_enabled && obj) {
        const unsigned nm = *((const unsigned char*)obj + 0x16);
        unsigned i;
        for (i = 0; i < nm && i < 8; ++i) {
            char* model = *(char**)((char*)obj + 0x1c + 4 * i);
            char* a; char* b;
            if (!model) continue;
            if (g_dbg < 6 && getenv("COD1RELOADED_HITBOX_DEBUG")) {
                unsigned q; g_dbg++;
                printf("%s xmodel %p:", TAG, model);
                for (q = 0; q < 0x40; q += 4) printf(" %08x", *(unsigned*)(model + q));
                printf("\n");
                for (q = 0; q < 12; ++q) {
                    const char* pp = *(const char**)(model + 4 * q);
                    if (readable(pp, 32)) printf("   +%02x -> %.32s\n", 4 * q, pp);
                }
                fflush(stdout);
            }
            a = *(char**)(model + 4);   if (!a) continue;
            b = *(char**)a;             if (!b) continue;
            patch_parts(*(void**)(b + 4), model);
        }
    }
    return g_orig(obj, start, end, prio, out);
}

void hitbox_fix_init(void) {
    const char* hm = getenv("COD1RELOADED_HEAD_ON_MESH");
    const char* e = getenv("COD1RELOADED_HITBOX_FIX");
    if (hm && *hm) g_head_on_mesh = atoi(hm) != 0;
    if (e && (e[0] == '0' || !strcmp(e, "off"))) {
        printf("%s off - shipped boxes (collar / overcoat / hands not hittable)\n", TAG);
        return;
    }
    if (memcmp((const void*)VA_PART_TEST, PROLOGUE, PATCH_LEN) != 0) {
        printf("%s engine bytes at 0x%08x are not the 1.5 per-part test - not installed\n", TAG, VA_PART_TEST);
        fflush(stdout);
        return;
    }
    if (hook_install(&g_hook, VA_PART_TEST, (uintptr_t)hook_part_test, PATCH_LEN) != 0) {
        printf("%s hook failed\n", TAG);
        fflush(stdout);
        return;
    }
    g_orig = (part_test_t)g_hook.trampoline;
    printf("%s on: %u body models + universal set, boxes grown to the mesh at first use"
           " (COD1RELOADED_HITBOX_FIX=0 to disable)\n", TAG, (unsigned)HB_NUM_SETS);
    fflush(stdout);
}
